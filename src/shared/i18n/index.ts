export type LanguageId = "pt-BR" | "en" | "es" | "ja" | "zh-CN" | "ko"

export type LanguageOption = {
  id: LanguageId
  nativeName: string
  shortName: string
}

export const DEFAULT_LANGUAGE: LanguageId = "pt-BR"

export const LANGUAGE_OPTIONS: readonly LanguageOption[] = [
  { id: "pt-BR", nativeName: "Português (Brasil)", shortName: "PT-BR" },
  { id: "en", nativeName: "English", shortName: "EN" },
  { id: "es", nativeName: "Español", shortName: "ES" },
  { id: "ja", nativeName: "日本語", shortName: "JA" },
  { id: "zh-CN", nativeName: "简体中文", shortName: "ZH-CN" },
  { id: "ko", nativeName: "한국어", shortName: "KO" },
] as const

export function isLanguage(value: unknown): value is LanguageId {
  return LANGUAGE_OPTIONS.some((option) => option.id === value)
}

let activeLanguage: LanguageId = DEFAULT_LANGUAGE
const graphemeSegmenters = new Map<LanguageId, Intl.Segmenter>()

export function setLanguage(language: LanguageId) {
  activeLanguage = language
}

export function getLanguage() {
  return activeLanguage
}

const UI_LOCALES: Record<LanguageId, string> = {
  "pt-BR": "pt-BR",
  en: "en-US",
  es: "es-ES",
  ja: "ja-JP",
  "zh-CN": "zh-CN",
  ko: "ko-KR",
}

export function formatUiDateTime(
  value: string | number | Date,
  options: Intl.DateTimeFormatOptions,
  language: LanguageId = activeLanguage,
) {
  const date = value instanceof Date ? value : new Date(value)
  if (Number.isNaN(date.getTime())) return ""
  return date.toLocaleString(UI_LOCALES[language], options)
}

